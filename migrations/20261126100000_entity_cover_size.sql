-- Размеры файла обложки в пикселях: браузер ставит карточке точное `aspect-ratio` до загрузки
-- картинки. Для постеров это мелочь (у них 2:3), для стены картин — главное: холсты бывают
-- и узкими, и панорамными, и без размеров стена один раз перестраивается после загрузки.
--
-- Заполняет тот, кто кладёт `cover_url` (импорт картин из Wikidata знает размер превью Commons);
-- неизвестно — NULL, тогда фронт как раньше держит место заглушкой.
ALTER TABLE entities
    ADD COLUMN cover_width int CHECK (cover_width > 0),
    ADD COLUMN cover_height int CHECK (cover_height > 0);
