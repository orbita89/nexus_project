-- Сериалы из TMDB (scripts/catalog-import/series_tmdb.py) — отдельный ключ `external_ids.tmdb_tv`,
-- а не общий `tmdb`. Две причины, обе ломающие:
--   1. У TMDB пространства id фильмов и сериалов независимы: id 1399 — и фильм, и «Игра
--      престолов». Общий `entities_external_tmdb_uq` отверг бы такой сериал как дубль фильма.
--   2. Условие `external_ids ? 'tmdb'` по всему каталогу означает «фильм из TMDB»: по нему
--      считается `visible` (без даты выхода — скрыт), «Пересобрать активные» гасит всё, что не
--      вошло в топ по баллу «Рекомендуемые» (а балл считается только для фильмов), и туда же
--      смотрит перенос в холодный архив. Сериалы под этим ключом гасли бы после первого же
--      пересчёта.
CREATE UNIQUE INDEX entities_external_tmdb_tv_uq ON entities (((external_ids ->> 'tmdb_tv')::int))
    WHERE external_ids ? 'tmdb_tv';
