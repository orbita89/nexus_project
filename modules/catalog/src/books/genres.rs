/// Название жанра по коду FB2; неизвестный код — `None`.
pub fn name(code: &str) -> Option<&'static str> {
    let key = code.trim().to_lowercase();
    GENRES
        .iter()
        .find(|(known, _)| *known == key)
        .map(|(_, title)| *title)
}

/// Названия жанров по кодам: без неизвестных и без повторов, порядок сохраняется.
pub fn names(codes: &[String]) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::with_capacity(codes.len());
    for code in codes {
        if let Some(title) = name(code) {
            if !out.contains(&title) {
                out.push(title);
            }
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_codes_are_named_and_unknown_skipped() {
        assert_eq!(name("sf_fantasy"), Some("Фэнтези"));
        assert_eq!(name(" SF_Fantasy "), Some("Фэнтези"));
        assert_eq!(name("my_own_genre"), None);
        let codes = ["sf_fantasy", "junk", "sf_fantasy", "sf"].map(String::from);
        assert_eq!(names(&codes), ["Фэнтези", "Научная фантастика"]);
    }
}
